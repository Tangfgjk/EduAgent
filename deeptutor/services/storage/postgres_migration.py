"""Verified native PostgreSQL business migration."""

import hashlib
import sqlite3

from psycopg import sql

from deeptutor.services.storage.postgres_adapter import connect_raw, schema_name, translate


def migrate(source):
    schema = schema_name(source)
    with sqlite3.connect(source.as_uri() + "?mode=ro", uri=True) as db, connect_raw() as pg:
        db.execute("BEGIN")
        if pg.execute(
            "SELECT 1 FROM information_schema.schemata WHERE schema_name=%s", (schema,)
        ).fetchone():
            raise RuntimeError("Target already exists; refusing overwrite: " + schema)
        pg.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
        pg.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(schema)))
        pg.execute(
            """CREATE FUNCTION wenjin_json(body text,path text) RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$ DECLARE v jsonb; BEGIN v=body::jsonb #> string_to_array(path,'.'); IF v='true'::jsonb THEN RETURN '1'; ELSIF v='false'::jsonb THEN RETURN '0'; ELSE RETURN v #>> '{}'; END IF; EXCEPTION WHEN invalid_text_representation THEN RETURN NULL; END $$"""
        )
        pg.execute(
            """CREATE FUNCTION wenjin_valid(body text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$ BEGIN PERFORM body::jsonb; RETURN TRUE; EXCEPTION WHEN invalid_text_representation THEN RETURN FALSE; END $$"""
        )
        tables = [
            r[0]
            for r in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
            )
        ]
        foreign = []
        summary = []
        for table in tables:
            q = '"' + table.replace('"', '""') + '"'
            columns = db.execute("PRAGMA table_info(" + q + ")").fetchall()
            defs = []
            identities = []
            pk = [c for c in columns if c[5]]
            for _, name, typ, notnull, default, key in columns:
                kind = (
                    "bigint"
                    if "INT" in typ.upper()
                    else "double precision"
                    if typ.upper() in ("REAL", "FLOAT", "DOUBLE")
                    else "bytea"
                    if typ.upper() == "BLOB"
                    else "text"
                )
                definition = sql.SQL("{} {}").format(sql.Identifier(name), sql.SQL(kind))
                if key and len(pk) == 1 and kind == "bigint":
                    definition += sql.SQL(" GENERATED BY DEFAULT AS IDENTITY")
                    identities.append(name)
                elif default is not None:
                    definition += sql.SQL(" DEFAULT " + str(default))
                if notnull:
                    definition += sql.SQL(" NOT NULL")
                defs.append(definition)
            defs.append(sql.SQL('"_legacy_rowid" bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE'))
            if pk:
                defs.append(
                    sql.SQL("PRIMARY KEY ({})").format(
                        sql.SQL(",").join(
                            sql.Identifier(c[1]) for c in sorted(pk, key=lambda c: c[5])
                        )
                    )
                )
            target = sql.Identifier(table)
            pg.execute(sql.SQL("CREATE TABLE {} ({})").format(target, sql.SQL(",").join(defs)))
            rows = db.execute("SELECT rowid,* FROM " + q).fetchall()
            names = ["_legacy_rowid"] + [c[1] for c in columns]
            with pg.cursor() as cur:
                with cur.copy(
                    sql.SQL("COPY {} ({}) FROM STDIN").format(
                        target, sql.SQL(",").join(map(sql.Identifier, names))
                    )
                ) as copy:
                    for row in rows:
                        copy.write_row(row)
            copied = pg.execute(
                sql.SQL('SELECT {} FROM {} ORDER BY "_legacy_rowid"').format(
                    sql.SQL(",").join(map(sql.Identifier, names)), target
                )
            ).fetchall()
            if sorted(rows) != copied:
                raise RuntimeError("Content verification failed: " + table)
            for name in identities + ["_legacy_rowid"]:
                pg.execute(
                    sql.SQL(
                        "SELECT setval(pg_get_serial_sequence(%s,%s), COALESCE(MAX({}),0)+1,false) FROM {}"
                    ).format(sql.Identifier(name), target),
                    (table, name),
                )
            for idx in db.execute("PRAGMA index_list(" + q + ")").fetchall():
                ddl = db.execute(
                    "SELECT sql FROM sqlite_master WHERE type='index' AND name=?", (idx[1],)
                ).fetchone()
                if ddl and ddl[0]:
                    pg.execute(translate(ddl[0]))
                elif idx[2] and idx[3] != "pk":
                    cols = [
                        c[2]
                        for c in db.execute(
                            'PRAGMA index_info("' + idx[1].replace('"', '""') + '")'
                        )
                    ]
                    pg.execute(
                        sql.SQL("CREATE UNIQUE INDEX {} ON {} ({})").format(
                            sql.Identifier(
                                "unique_"
                                + hashlib.sha256((table + idx[1]).encode()).hexdigest()[:16]
                            ),
                            target,
                            sql.SQL(",").join(map(sql.Identifier, cols)),
                        )
                    )
            groups = {}
            for fk in db.execute("PRAGMA foreign_key_list(" + q + ")"):
                groups.setdefault(fk[0], []).append(fk)
            for group in groups.values():
                foreign.append((table, sorted(group, key=lambda f: f[1])))
            summary.append({"table": table, "rows": len(rows)})
        for table, group in foreign:
            pg.execute(
                sql.SQL(
                    "ALTER TABLE {} ADD FOREIGN KEY ({}) REFERENCES {} ({}) ON UPDATE {} ON DELETE {}"
                ).format(
                    sql.Identifier(table),
                    sql.SQL(",").join(sql.Identifier(f[3]) for f in group),
                    sql.Identifier(group[0][2]),
                    sql.SQL(",").join(sql.Identifier(f[4]) for f in group),
                    sql.SQL(group[0][5]),
                    sql.SQL(group[0][6]),
                )
            )
        return {
            "source": str(source),
            "schema": schema,
            "tables": summary,
            "status": "verified_not_active",
        }


def migrate_accounts(source):
    """Migrate canonical accounts without overwriting an active registry."""
    import json

    from psycopg.types.json import Jsonb

    from deeptutor.multi_user.models import VALID_ROLES

    users = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(users, dict):
        raise ValueError("Invalid account source")
    if any(
        not isinstance(record, dict)
        or not record.get("id")
        or record.get("role") not in VALID_ROLES
        for record in users.values()
    ):
        raise ValueError("Canonical account ids and roles required before migration")
    with connect_raw() as c:
        c.execute("SELECT pg_advisory_xact_lock(981307126)")
        c.execute(
            "CREATE TABLE IF NOT EXISTS account_records (user_id text PRIMARY KEY,username text NOT NULL UNIQUE,role text NOT NULL CHECK(role IN ('admin','teacher','student','user')),body jsonb NOT NULL)"
        )
        existing = dict(c.execute("SELECT username,body FROM account_records").fetchall())
        if existing and existing != users:
            raise RuntimeError(
                "Account registry already contains different data; refusing overwrite"
            )
        for username, record in users.items():
            c.execute(
                "INSERT INTO account_records VALUES (%s,%s,%s,%s) ON CONFLICT(username) DO NOTHING",
                (record["id"], username, record["role"], Jsonb(record)),
            )
        if dict(c.execute("SELECT username,body FROM account_records").fetchall()) != users:
            raise RuntimeError("Account migration verification failed")
    return {"accounts": len(users), "verified": True, "status": "verified_not_active"}
