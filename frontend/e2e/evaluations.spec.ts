import { test, expect } from '@playwright/test';

test('评测工作台：真实报告、同条件对比、复核保存与手机布局', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/admin/');
  await page.getByLabel('账号', { exact: true }).fill('s03.admin');
  await page.getByLabel('密码', { exact: true }).fill('S03-test-only-password!');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('link', { name: '评测工作台', exact: true }).click();
  await expect(page.getByText('全部尝试中返回可用结果：16 / 18。失败及重复均保留。', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '评测检查未通过', exact: true })).toBeVisible();
  await expect(page.getByText('工程失败 2', { exact: false })).toBeVisible();
  await page.getByLabel('仅显示不符合开发参考的条目', { exact: true }).check();
  await expect(page.locator('section.card').filter({ has: page.getByRole('heading', { name: /^teach-live:/ }) })).toHaveCount(2);
  await page.getByLabel('评测运行', { exact: true }).selectOption('multiturn-v2-live');
  await page.getByLabel('右侧对照报告', { exact: true }).selectOption('multiturn-v3-live');
  await expect(page.getByText('改善 3 · 退步 0', { exact: false })).toBeVisible();
  await page.getByLabel('评测运行', { exact: true }).selectOption('teach-multiturn-live');
  await expect(page.getByText('全部尝试中返回可用结果：6 / 6。失败及重复均保留。', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '待逐条人工复核', exact: true })).toBeVisible();
  await page.getByLabel('评测运行', { exact: true }).selectOption('roundtable-live');
  await expect(page.getByRole('heading', { name: '圆桌 · 三角色分工与语义复核', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '评测检查未通过', exact: true })).toBeVisible();
  const roundtableRow = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'roundtable-live:R02', exact: true }) });
  await expect(roundtableRow.getByText('质疑者', { exact: true })).toBeVisible();
  await page.getByLabel('评测运行', { exact: true }).selectOption('planning-live');
  await expect(page.getByRole('heading', { name: '规划 · 引用与建议语义复核', exact: true })).toBeVisible();
  await expect(page.getByText('全部尝试中返回可用结果：2 / 3。失败及重复均保留。', { exact: true })).toBeVisible();
  await page.getByLabel('评测运行', { exact: true }).selectOption('teach-fake');
  const row = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'teach-fake:T01', exact: true }) });
  await row.getByLabel('复核结论').selectOption('model_issue');
  await row.getByLabel('复核依据', { exact: true }).fill('浏览器验收：固定模拟输出只能验证工程流程，问题语义须独立复核。');
  await row.getByRole('button', { name: '保存复核记录', exact: true }).click();
  await expect(row.getByText('复核记录已保存', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByLabel('评测运行', { exact: true }).selectOption('teach-fake');
  await expect(row.getByText('查看已有复核意见（1 条）', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
